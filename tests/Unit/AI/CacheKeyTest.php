<?php

declare(strict_types=1);

namespace Tests\Unit\AI;

use App\AI\Capability;
use App\AI\Requests\TextGenerationRequest;
use App\AI\Requests\TranslationRequest;
use App\AI\ResolvedModel;
use PHPUnit\Framework\Attributes\Test;
use PHPUnit\Framework\TestCase;

/**
 * Cache identity, which is easy to get subtly wrong and expensive when you do.
 *
 * A key that is too broad serves one user's answer to another. A key that is
 * too narrow never hits and the cache silently does nothing. The failure mode
 * that costs the most, though, is the one covered last here: a key that
 * ignores the prompt version, so editing a prompt keeps serving results
 * generated by the old one and the change looks like it did nothing.
 */
final class CacheKeyTest extends TestCase
{
    private function model(string $key = 'fast'): ResolvedModel
    {
        return new ResolvedModel(
            key: $key,
            provider: 'anthropic',
            apiId: 'claude-haiku-4-5',
            capabilities: [Capability::TextGeneration, Capability::Translation],
        );
    }

    #[Test]
    public function identical_requests_share_a_key(): void
    {
        $a = new TextGenerationRequest(userPrompt: 'Describe a hotel.');
        $b = new TextGenerationRequest(userPrompt: 'Describe a hotel.');

        $this->assertSame($a->cacheKey($this->model()), $b->cacheKey($this->model()));
    }

    #[Test]
    public function a_different_prompt_changes_the_key(): void
    {
        $this->assertNotSame(
            (new TextGenerationRequest(userPrompt: 'A'))->cacheKey($this->model()),
            (new TextGenerationRequest(userPrompt: 'B'))->cacheKey($this->model()),
        );
    }

    #[Test]
    public function every_option_that_changes_the_output_changes_the_key(): void
    {
        $base = new TextGenerationRequest(userPrompt: 'Same prompt.');
        $key = $base->cacheKey($this->model());

        $variants = [
            'system prompt' => new TextGenerationRequest(userPrompt: 'Same prompt.', systemPrompt: 'Be terse.'),
            'temperature' => new TextGenerationRequest(userPrompt: 'Same prompt.', temperature: 0.1),
            'max tokens' => new TextGenerationRequest(userPrompt: 'Same prompt.', maxTokens: 100),
        ];

        foreach ($variants as $label => $variant) {
            $this->assertNotSame($key, $variant->cacheKey($this->model()), "{$label} must affect the key.");
        }
    }

    #[Test]
    public function a_different_model_changes_the_key(): void
    {
        $request = new TextGenerationRequest(userPrompt: 'Same prompt.');

        // Same prompt, different model, different answer. Sharing a cache
        // entry across models would serve haiku output as if it were opus.
        $this->assertNotSame(
            $request->cacheKey($this->model('fast')),
            $request->cacheKey($this->model('slow')),
        );
    }

    #[Test]
    public function the_prompt_version_changes_the_key(): void
    {
        // The field people forget. Without it, editing the prompt-building
        // code keeps serving results the previous version produced.
        $this->assertNotSame(
            (new TextGenerationRequest(userPrompt: 'Same.', promptVersion: 1))->cacheKey($this->model()),
            (new TextGenerationRequest(userPrompt: 'Same.', promptVersion: 2))->cacheKey($this->model()),
        );
    }

    #[Test]
    public function different_capabilities_never_collide(): void
    {
        // Contrived, but the guarantee matters: the capability is part of the
        // key, so two capabilities can never share an entry even if their
        // payloads happened to serialise identically.
        $this->assertNotSame(
            (new TextGenerationRequest(userPrompt: 'Hello'))->cacheKey($this->model()),
            (new TranslationRequest(text: 'Hello', targetLanguage: 'FR'))->cacheKey($this->model()),
        );
    }

    #[Test]
    public function the_key_is_a_sha256_hash(): void
    {
        // Fixed width, safe as a database primary key and as a cache key in
        // any driver — unlike a raw prompt, which can be megabytes.
        $this->assertMatchesRegularExpression(
            '/^[0-9a-f]{64}$/',
            (new TextGenerationRequest(userPrompt: 'Hi'))->cacheKey($this->model()),
        );
    }

    #[Test]
    public function it_survives_multibyte_payloads(): void
    {
        $request = new TranslationRequest(text: 'سلام دنیا', targetLanguage: 'EN');

        $this->assertMatchesRegularExpression('/^[0-9a-f]{64}$/', $request->cacheKey($this->model()));
        $this->assertNotSame(
            $request->cacheKey($this->model()),
            (new TranslationRequest(text: 'سلام', targetLanguage: 'EN'))->cacheKey($this->model()),
        );
    }
}
