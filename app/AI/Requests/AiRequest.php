<?php

declare(strict_types=1);

namespace App\AI\Requests;

use App\AI\Capability;
use App\AI\ProviderFactory;
use App\AI\ResolvedModel;
use App\AI\Results\AiResult;

/**
 * One unit of AI work, as a command object that knows how to run itself.
 *
 * The dispatch lives here rather than in the gateway, and that is the single
 * decision the extensibility of this layer rests on. An earlier draft gave the
 * gateway a `complete()` method; it would then have needed `translate()`,
 * `generateVideo()`, `transcribe()` — every new modality editing one central
 * class, which is Open/Closed violated in the most direct way possible.
 *
 * Because each request asks the factory for the exact provider type it needs,
 * the gateway never learns how many kinds of AI work exist. Adding video
 * generation is a new subclass here plus a new interface: nothing already
 * written changes.
 */
abstract readonly class AiRequest
{
    abstract public function capability(): Capability;

    /**
     * Run this request against whichever provider serves its capability.
     *
     * Implementations call the factory method matching their capability —
     * `$factory->textGenerator($model)` — which returns a narrowly-typed
     * provider. That is what makes "this provider cannot do this" a static
     * type error rather than a runtime assertion.
     */
    abstract public function executeOn(ProviderFactory $factory, ResolvedModel $model): AiResult;

    /**
     * Everything that changes the output, normalised for hashing.
     *
     * Two requests with the same payload must be interchangeable, so anything
     * that would alter the result belongs here — and anything that would not
     * (a request id, a timestamp) must stay out, or the cache never hits.
     *
     * @return array<string, mixed>
     */
    abstract public function cachePayload(): array;

    /**
     * Bumped by hand whenever the prompt-building code changes.
     *
     * This is the field people forget. Without it, editing a prompt in code
     * silently keeps serving results generated by the previous version, and
     * the bug looks like "my change did nothing".
     */
    public function promptVersion(): int
    {
        return 1;
    }

    /**
     * Identity of this call for caching purposes.
     *
     * Never just "input + model": the capability, the resolved model, and the
     * prompt version are all part of what produced the answer.
     */
    public function cacheKey(ResolvedModel $model): string
    {
        $payload = $this->cachePayload();
        ksort($payload);

        return hash('sha256', implode('|', [
            $this->capability()->value,
            $model->key,
            $this->promptVersion(),
            json_encode($payload, JSON_THROW_ON_ERROR | JSON_UNESCAPED_UNICODE),
        ]));
    }
}
